"""Write a label snapshot's sanitized report: aggregate JSON plus a Markdown summary.

The report holds counts and distributions only (see audit.py); no participant id or date.
"""

import json
from pathlib import Path
from typing import Any


def _table(rows: list[tuple[Any, ...]], header: tuple[str, ...]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def _dist(d: dict | None) -> str:
    if not d:
        return "none"
    spread = f"IQR {d['p25']} to {d['p75']}, range {d['min']} to {d['max']}"
    return f"median {d['median']} ({spread}, n={d['n']})"


def render_markdown(report: dict[str, Any]) -> str:
    a = report["audit"]
    p, e, t, w = a["participants"], a["episodes"], a["tests"], a["onset_windows"]
    c, u = a["control_follow_up"], a["status_unknown"]
    out = [
        f"# Outcome labels: `{report['snapshot_id']}`",
        "",
        f"Generated by `python -I -m hachi.data.clinical build {a['dataset_id']}` from commit "
        f"`{report['built_with']['git_sha'][:12]}`. Definitions `{report['definitions_version']}` "
        f"(`configs/outcomes/definitions.toml`, sha256 `{report['definitions_sha256'][:12]}`). "
        f"Clock: `{a['clock']}`. Aggregate counts only.",
        "",
        "## Sources",
        "",
        _table(
            [
                (name, f"{s['bytes']:,}", f"`{s['sha256']}`")
                for name, s in report["sources"].items()
            ],
            ("File", "Bytes", "SHA-256"),
        ),
        "",
        "## Participants",
        "",
        _table(sorted(p.items()), ("Participants", "Count")),
        "",
        f"Control follow-up (participants outside the label tables): {c['participants']} "
        f"participants, {c['wearable_days']:,} wearable days, "
        f"{_dist(c['wearable_days_per_participant'])} days each; "
        f"{c['completed_survey_days']} completed survey days.",
        "",
        "## Episodes and tests",
        "",
        _table(
            sorted(e["by_category_and_confidence"].items()), ("Category:confidence", "Episodes")
        ),
        "",
        f"Onset precision (interval width in local days): {e['onset_interval_days']}. "
        f"Episodes merging a relapse onset: {e['with_merged_relapse_onsets']}.",
        "",
        "Wearable coverage in the 28 days before onset:",
        "",
        _table(
            sorted(e["pre_onset_wearable_coverage_28d"].items()), ("Category:measure", "Episodes")
        ),
        "",
        f"Tests: {t['total']} ({t['by_pathogen_and_result']}); {t['linked_to_episode']} "
        f"linked to an episode, {t['unlinked']} unlinked. Test day minus onset day, linked: "
        f"{_dist(t['test_day_minus_onset_day_linked'])}; unlinked tests in participants with an "
        f"episode: {_dist(t['test_day_minus_nearest_onset_day_unlinked'])}.",
        "",
        "## Recovery endpoints",
        "",
    ]
    canonical = report["canonical_recovery_endpoint"]
    for ident, r in a["recovery"].items():
        mark = " (canonical: `outcomes.parquet`)" if ident == canonical else ""
        out += [
            f"**`{ident}`**{mark}: {r['episodes']} episodes, by reason {r['by_reason']}. "
            f"Days from onset to resolution, earliest {_dist(r['days_to_resolution_min'])}; "
            f"latest {_dist(r['days_to_resolution_max'])}. Censored follow-up: "
            f"{_dist(r['days_followed_censored'])} days.",
            "",
        ]
    out += ["## Onset windows (cutoffs at local midnight)", ""]
    if w.get("cutoffs"):
        horizons = [k for k in w if k.endswith("h")]
        labels = sorted({lab for h in horizons for lab in w[h]["onset_labels"]})
        rows = [(lab, *(w[h]["onset_labels"].get(lab, 0) for h in horizons)) for lab in labels]
        rows.append(
            (
                "**at-risk denominator** (positive + negative)",
                *(w[h]["at_risk_denominator"] for h in horizons),
            )
        )
        rows.append(
            (
                "participants with a positive window",
                *(w[h]["participants_with_a_positive_window"] for h in horizons),
            )
        )
        out += [
            f"{w['cutoffs']:,} cutoffs, {w['cutoffs_with_wearable_records_day_before']:,} with "
            "wearable records the day before.",
            "",
            _table(rows, ("Onset label", *horizons)),
            "",
            _table(
                [
                    (lab, *(w[h]["test_labels"].get(lab, 0) for h in horizons))
                    for lab in sorted({x for h in horizons for x in w[h]["test_labels"]})
                ],
                ("Positive-test target", *horizons),
            ),
            "",
        ]
    out += [
        f"Unknown status: {u['rows']} periods, {u['days']:,} days.",
        "",
        "## Source and label checks",
        "",
        _table(sorted(a["source_counts"].items()), ("Source count", "Value")),
        "",
        _table(sorted(a["label_issues"].items()), ("Label issue", "Count")),
        "",
    ]
    if "wearable_archive" in a:
        wa = a["wearable_archive"]
        out += [
            "Wearable archive: "
            + "; ".join(f"{k.replace('_', ' ')}: {v}" for k, v in sorted(wa.items())),
            "",
        ]
    out += ["## Tables", "", _table(sorted(report["tables"].items()), ("Table", "Rows")), ""]
    return "\n".join(out)


def write_report(report: dict[str, Any], directory: Path) -> tuple[Path, Path]:
    directory.mkdir(parents=True, exist_ok=True)
    stem = report["snapshot_id"].rsplit("-", 1)[0]
    js = directory / f"{stem}.json"
    md = directory / f"{stem}.md"
    js.write_text(json.dumps(report, indent=2, sort_keys=True, default=str) + "\n")
    md.write_text(render_markdown(report))
    return js, md
