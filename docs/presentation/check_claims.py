#!/usr/bin/env python3
"""Verify public source pins and render a presentation without reading private data."""

import argparse
import hashlib
import json
import re
import string
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
TOKEN = re.compile(r"\{\{([a-z][a-z0-9-]*)\}\}")


def has_unbound_numeral(text):
    prose = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    prose = re.sub(r"#\d+|Chronos-2|COVID-19|phase1|SHA256", "", prose)
    return bool(re.search(r"\d", prose))


def git(*args):
    return subprocess.check_output(["git", "-C", str(ROOT), *args], stderr=subprocess.DEVNULL)


def pointer(document, path):
    if not path.startswith("/"):
        raise ValueError("invalid JSON pointer")
    for key in path[1:].split("/"):
        key = key.replace("~1", "/").replace("~0", "~")
        document = document[int(key)] if isinstance(document, list) else document[key]
    return document


def render(manifest):
    if manifest["format"] != "hachi-public-claims-1":
        raise ValueError("unsupported manifest")
    if (
        manifest["completion"] != "preparation_only"
        or manifest["final_test_authorized"] is not False
    ):
        raise ValueError("preparation cannot grant completion or test authority")
    sources = manifest["sources"]
    documents = {}
    for name, source in sources.items():
        path = source["path"]
        # Read only explicitly reviewed repository sources, never arbitrary local paths.
        if Path(path).is_absolute() or ".." in Path(path).parts:
            raise ValueError("unsafe source path")
        if (
            not path.startswith(("reports/", "docs/", "configs/", "src/hachi/data/"))
            and path != "scripts/rehearsal/README.md"
        ):
            raise ValueError("source outside public evidence scope")
        if path.startswith("reports/models/recovery/"):
            raise ValueError("superseded recovery evidence is excluded")
        commit = source["commit"]
        if not re.fullmatch(r"[0-9a-f]{40}", commit):
            raise ValueError("source requires a full Git commit")
        git("merge-base", "--is-ancestor", commit, "HEAD")
        committed = git("show", f"{commit}:{path}")
        local = ROOT / path
        if local.is_symlink() or not local.is_file():
            raise ValueError("source must be a regular repository file")
        if committed != local.read_bytes():
            raise ValueError(f"source drift: {name}")
        if hashlib.sha256(committed).hexdigest() != source["sha256"]:
            raise ValueError(f"source digest mismatch: {name}")
        documents[name] = json.loads(committed) if path.endswith(".json") else committed.decode()

    claims = {}
    appendix = [
        "# Claim and source ledger",
        "",
        "Generated by `check_claims.py`; do not edit.",
        "",
        "Pins establish traceability to reviewed public evidence. They do not recompute metrics,",
        "verify private artifacts, certify scientific acceptance or authorize test opening.",
        "",
    ]
    for claim in manifest["claims"]:
        identifier = claim["id"]
        if not re.fullmatch(r"[a-z][a-z0-9-]*", identifier) or identifier in claims:
            raise ValueError("invalid or duplicate claim id")
        values = {}
        bindings = []
        for field, binding in claim["values"].items():
            document = documents[binding["source"]]
            if "pointer" in binding:
                actual = pointer(document, binding["pointer"])
                selector = binding["pointer"]
            else:
                actual = binding["expected"]
                selector = "exact text anchor"
                if (
                    not isinstance(document, str)
                    or not isinstance(actual, str)
                    or actual not in document
                ):
                    raise ValueError(f"text anchor mismatch: {identifier}")
            expected = binding["expected"]
            if type(actual) is not type(expected) or actual != expected:
                raise ValueError(f"claim value mismatch: {identifier}")
            if not isinstance(actual, (str, int, float, bool)) and actual is not None:
                raise ValueError("claim bindings must be scalar")
            values[field] = actual
            bindings.append((field, binding["source"], selector, expected))
        parts = list(string.Formatter().parse(claim["text"]))
        if has_unbound_numeral("".join(literal for literal, _, _, _ in parts)):
            raise ValueError(f"unbound numeral in claim: {identifier}")
        used = {field for _, field, _, _ in parts if field}
        if used != set(values):
            raise ValueError(f"claim fields mismatch: {identifier}")
        text = claim["text"].format(**values)
        claims[identifier] = f"{text} [Evidence](CLAIMS.md#{identifier})."
        appendix += [f"## {identifier}", "", text, "", f"Limit: {claim['limit']}", ""]
        for field, name, selector, expected in bindings:
            appendix.append(
                f"- `{field}`: source `{name}`, selector `{selector}`, "
                f"exact value `{json.dumps(expected, ensure_ascii=True)}`."
            )
        appendix.append("")
    appendix += ["## Source pins", ""]
    for name, source in sources.items():
        link = f"https://github.com/vibemonkies/hachi/blob/{source['commit']}/{source['path']}"
        appendix += [
            f"### {name}",
            "",
            f"[{source['path']}]({link})",
            "",
            f"File SHA256: `{source['sha256']}`.",
            "",
            f"Scope: {source['scope']}",
            "",
        ]

    template = (HERE / "NARRATIVE.template.md").read_text()
    # Measured numerals belong in source-bound claims; identifiers may remain prose.
    if has_unbound_numeral(TOKEN.sub("", template)):
        raise ValueError("unbound numeral in narrative template")
    used = set(TOKEN.findall(template))
    if used != set(claims):
        raise ValueError("unknown or unused narrative claims")
    narrative = TOKEN.sub(lambda match: claims[match[1]], template)
    if "{{" in narrative or "}}" in narrative:
        raise ValueError("unresolved narrative token")
    return {"NARRATIVE.md": narrative, "CLAIMS.md": "\n".join(appendix)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--write", action="store_true", help="write generated Markdown after verification"
    )
    args = parser.parse_args()
    try:
        manifest = json.loads((HERE / "claims.json").read_text())
        outputs = render(manifest)
        for name, contents in outputs.items():
            destination = HERE / name
            if args.write:
                destination.write_text(contents)
            elif not destination.is_file() or destination.read_text() != contents:
                raise ValueError(f"generated document drift: {name}")
        print(
            json.dumps(
                {
                    "status": "passed",
                    "claims": len(manifest["claims"]),
                    "sources": len(manifest["sources"]),
                    "checkout_commit": git("rev-parse", "HEAD").decode().strip(),
                    "manifest_sha256": hashlib.sha256(
                        (HERE / "claims.json").read_bytes()
                    ).hexdigest(),
                    "checker_sha256": hashlib.sha256(
                        (HERE / "check_claims.py").read_bytes()
                    ).hexdigest(),
                    "documents_sha256": {
                        name: hashlib.sha256(contents.encode()).hexdigest()
                        for name, contents in outputs.items()
                    },
                    "python": sys.version.split()[0],
                    "checkout_dirty": bool(git("status", "--porcelain")),
                    "completion": "preparation_only",
                    "final_test_authorized": False,
                }
            )
        )
        return 0
    except (ValueError, KeyError, IndexError, TypeError, OSError, subprocess.CalledProcessError):
        # Never echo source values, paths from exceptions, or raw subprocess output.
        print(
            "Claim check failed: inspect public source pins, selectors and generated documents.",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    sys.exit(main())
